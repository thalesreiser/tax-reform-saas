// Generates the engine client's types and decimal maps from the committed OpenAPI documents
// (openapi/<engine>.json, checked against the running engines in CI). Run with `pnpm generate`.
//
// The engines declare their BigDecimal fields as `type: number` but send them as JSON strings
// ("42.24"). Every `type: number` therefore becomes `DecimalText` in the types, and the decimal map
// lists where those fields are, so the client turns exactly them into decimals.
//
// Usage: node scripts/generate.mjs [package-dir]
import { readFile, writeFile } from "node:fs/promises"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import openapiTS, { astToString } from "openapi-typescript"
import ts from "typescript"

const pkg = process.argv[2] ?? join(dirname(fileURLToPath(import.meta.url)), "..")
const ENGINES = ["regime-regular", "simples-nacional"]
const HEADER = "// Generated by scripts/generate.mjs from openapi/{0}.json. Do not edit.\n"
const DECIMAL = ts.factory.createTypeReferenceNode("DecimalText")

const isNumber = (schema) => schema.type === "number"
const refName = (ref) => ref.replace("#/components/schemas/", "")

/** Shape of the decimal fields under a schema, or undefined when it has none. */
function shapeOf(schema, schemas, seen) {
  if (!schema || typeof schema !== "object") return undefined
  if (schema.$ref) {
    const name = refName(schema.$ref)
    return hasDecimals(name, schemas, seen) ? { ref: name } : undefined
  }
  if (isNumber(schema)) return "decimal"
  if (schema.items) {
    const items = shapeOf(schema.items, schemas, seen)
    return items && { items }
  }
  const props = {}
  for (const part of [schema, ...(schema.allOf ?? [])]) {
    for (const [key, value] of Object.entries(part.properties ?? {})) {
      const shape = shapeOf(value, schemas, seen)
      if (shape) props[key] = shape
    }
  }
  return Object.keys(props).length > 0 ? { props } : undefined
}

function hasDecimals(name, schemas, seen) {
  if (seen.has(name)) return seen.get(name)
  seen.set(name, false) // cycle guard
  const result = shapeOf(schemas[name], schemas, seen) !== undefined
  seen.set(name, result)
  return result
}

for (const engine of ENGINES) {
  const spec = JSON.parse(await readFile(join(pkg, "openapi", `${engine}.json`), "utf8"))
  const header = HEADER.replace("{0}", engine)

  const ast = await openapiTS(spec, {
    transform: (schema) => (isNumber(schema) ? DECIMAL : undefined),
  })
  const types = `${header}import type { DecimalText } from "../decimal-text.js"\n\n${astToString(ast)}`
  await writeFile(join(pkg, "src", "generated", `${engine}.ts`), types)

  const schemas = spec.components.schemas
  const seen = new Map()
  const shapes = {}
  for (const name of Object.keys(schemas).sort()) {
    const shape = hasDecimals(name, schemas, seen) && shapeOf(schemas[name], schemas, seen)
    if (shape) shapes[name] = shape
  }
  const map = `${header}import type { DecimalShape } from "../decimals.js"

export const decimalShapes = ${JSON.stringify(shapes, null, 2)} as const satisfies Record<string, DecimalShape>
`
  await writeFile(join(pkg, "src", "generated", `${engine}-decimals.ts`), map)
}
