import { afterEach, describe, expect, it } from "vitest"
import { z } from "zod"
import { type App, REQUEST_ID_HEADER, buildApp } from "../src/app.js"
import { loadConfig } from "../src/config.js"
import { PROBLEM_CONTENT_TYPE, problemSchema } from "../src/problem.js"
import { healthResponseSchema } from "../src/routes/health.js"
import { TEST_ENV } from "./env.js"

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/

let app: App | undefined

async function start(extra?: (app: App) => void): Promise<App> {
  app = await buildApp(loadConfig({ ...TEST_ENV, APP_VERSION: "1.2.3" }))
  extra?.(app)
  await app.ready()
  return app
}

afterEach(async () => {
  await app?.close()
  app = undefined
})

describe("GET /health", () => {
  it("returns ok with the version", async () => {
    const res = await (await start()).inject({ method: "GET", url: "/health" })
    expect(res.statusCode).toBe(200)
    const body = healthResponseSchema.parse(res.json())
    expect(body.version).toBe("1.2.3")
  })
})

describe("client address behind a proxy", () => {
  async function ipSeen(env: Record<string, string>) {
    app = await buildApp(loadConfig({ ...TEST_ENV, ...env }))
    app.get("/test/ip", (request) => ({ ip: request.ip }))
    await app.ready()
    const res = await app.inject({
      method: "GET",
      url: "/test/ip",
      remoteAddress: "10.0.0.1",
      // The first entry is what a client could send itself; the proxy appended the last one.
      headers: { "x-forwarded-for": "198.51.100.9, 203.0.113.7" },
    })
    return res.json<{ ip: string }>().ip
  }

  it("ignores X-Forwarded-For by default", async () => {
    expect(await ipSeen({})).toBe("10.0.0.1")
  })

  it("trusts only the configured hop (Fly.io)", async () => {
    expect(await ipSeen({ TRUST_PROXY_HOPS: "1" })).toBe("203.0.113.7")
  })
})

describe("request id", () => {
  it("is generated by the server and never echoes the client's value", async () => {
    const res = await (
      await start()
    ).inject({
      method: "GET",
      url: "/health",
      headers: { [REQUEST_ID_HEADER]: "client-chosen<script>" },
    })
    const id = res.headers[REQUEST_ID_HEADER]
    expect(id).toMatch(UUID)
    expect(id).not.toBe("client-chosen<script>")
  })
})

describe("problem details", () => {
  it("answers unknown routes with 404 problem+json", async () => {
    const res = await (await start()).inject({ method: "GET", url: "/nope" })
    expect(res.statusCode).toBe(404)
    expect(res.headers["content-type"]).toContain(PROBLEM_CONTENT_TYPE)
    const body = problemSchema.parse(res.json())
    expect(body).toMatchObject({ status: 404, title: "Not Found", type: "about:blank" })
    expect(body.requestId).toBe(res.headers[REQUEST_ID_HEADER])
  })

  it("lists each invalid field on validation errors", async () => {
    const api = await start((a) => {
      a.post(
        "/validate",
        { schema: { body: z.object({ cnpj: z.string().length(14), amount: z.string() }) } },
        // Never reflect the request body: it would be an XSS sink and carries fiscal data.
        () => ({ accepted: true }),
      )
    })
    const res = await api.inject({ method: "POST", url: "/validate", payload: { cnpj: "123" } })
    expect(res.statusCode).toBe(400)
    expect(res.headers["content-type"]).toContain(PROBLEM_CONTENT_TYPE)
    const body = problemSchema.parse(res.json())
    expect(body.errors?.map((e) => e.pointer).sort()).toEqual(["/amount", "/cnpj"])
    expect(body.errors?.every((e) => e.location === "body")).toBe(true)
  })

  it("keeps the message of other 4xx errors", async () => {
    const api = await start((a) => {
      a.get("/teapot", () => {
        throw Object.assign(new Error("No coffee here."), { statusCode: 418 })
      })
    })
    const body = problemSchema.parse((await api.inject({ method: "GET", url: "/teapot" })).json())
    expect(body).toMatchObject({ status: 418, detail: "No coffee here." })
  })

  it("hides the cause of 5xx errors", async () => {
    const api = await start((a) => {
      a.get("/boom", () => {
        throw new Error("database password is hunter2")
      })
    })
    const res = await api.inject({ method: "GET", url: "/boom" })
    expect(res.statusCode).toBe(500)
    expect(res.body).not.toContain("hunter2")
    expect(problemSchema.parse(res.json())).toMatchObject({
      status: 500,
      title: "Internal Server Error",
    })
  })
})

describe("GET /openapi.json", () => {
  it("publishes an OpenAPI 3.1 document with the health route", async () => {
    const res = await (await start()).inject({ method: "GET", url: "/openapi.json" })
    const doc = z
      .object({
        openapi: z.string(),
        info: z.object({ version: z.string() }),
        paths: z.record(z.string(), z.unknown()),
      })
      .parse(res.json())
    expect(doc.openapi).toBe("3.1.0")
    expect(doc.info.version).toBe("1.2.3")
    expect(Object.keys(doc.paths)).toContain("/health")
    expect(Object.keys(doc.paths)).toEqual(
      expect.arrayContaining(["/v1/clients", "/v1/cnpj/{cnpj}"]),
    )
    expect(Object.keys(doc.paths)).not.toContain("/openapi.json")
  })
})
